  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX audit_log_entity_idx ON audit_log (entity, entity_id, created_at DESC);

-- ---------------------------------------------------------------------
-- Phase actions used by the Director (call these from your API)
-- ---------------------------------------------------------------------

-- Mark a phase completed and close all its records. Returns the number of records closed.
CREATE OR REPLACE FUNCTION complete_phase(p_phase uuid, p_user uuid) RETURNS integer
LANGUAGE plpgsql AS $$
DECLARE n integer;
BEGIN
  UPDATE phases SET status = 'Completed', completed_at = now()
   WHERE id = p_phase AND status = 'Active';
  IF NOT FOUND THEN RAISE EXCEPTION 'Phase not found or already completed'; END IF;
  UPDATE employees SET closed_at = now(), closed_by = p_user
   WHERE phase_id = p_phase AND closed_at IS NULL;
  GET DIAGNOSTICS n = ROW_COUNT;
  INSERT INTO audit_log (user_id, action, entity, entity_id, details)
  VALUES (p_user, 'complete_phase', 'phase', p_phase, jsonb_build_object('records_closed', n));
  RETURN n;
END $$;

-- Reopen a completed phase and unlock its records. Returns the number of records unlocked.
CREATE OR REPLACE FUNCTION reopen_phase(p_phase uuid, p_user uuid) RETURNS integer
LANGUAGE plpgsql AS $$
DECLARE n integer;
BEGIN
  UPDATE phases SET status = 'Active', completed_at = NULL
   WHERE id = p_phase AND status = 'Completed';
  IF NOT FOUND THEN RAISE EXCEPTION 'Phase not found or not completed'; END IF;
  UPDATE employees SET closed_at = NULL, closed_by = NULL
   WHERE phase_id = p_phase AND closed_at IS NOT NULL;
  GET DIAGNOSTICS n = ROW_COUNT;
  INSERT INTO audit_log (user_id, action, entity, entity_id, details)
  VALUES (p_user, 'reopen_phase', 'phase', p_phase, jsonb_build_object('records_unlocked', n));
  RETURN n;
END $$;

-- Permanently delete a completed phase with its records and file rows.
-- Returns the Vercel Blob URLs of the deleted files so the API can delete them from Blob storage.
CREATE OR REPLACE FUNCTION delete_completed_phase(p_phase uuid, p_user uuid) RETURNS TABLE (blob_url text)
LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM phases WHERE id = p_phase AND status = 'Completed') THEN
    RAISE EXCEPTION 'Only a completed phase can be deleted';
  END IF;
  RETURN QUERY
    SELECT f.blob_url FROM files f JOIN employees e ON e.id = f.employee_id
     WHERE e.phase_id = p_phase AND f.blob_url IS NOT NULL;
  INSERT INTO audit_log (user_id, action, entity, entity_id)
  VALUES (p_user, 'delete_phase', 'phase', p_phase);
  DELETE FROM phases WHERE id = p_phase;
END $$;

-- ---------------------------------------------------------------------
-- Views for the dashboard cards, charts and family quota statistics
-- ---------------------------------------------------------------------
CREATE VIEW v_employee_verification AS
SELECT e.*,
       CASE
         WHEN 'Not verified' IN (e.matric_status, e.fsc_status, e.ba_status, e.prof_status) THEN 'Has not verified'
         WHEN 'Pending'      IN (e.matric_status, e.fsc_status, e.ba_status, e.prof_status) THEN 'Has pending'
         ELSE 'Fully verified'
       END AS verification
FROM employees e;

CREATE VIEW v_phase_stats AS
SELECT p.id AS phase_id, p.name AS phase, p.status, e.district,
       count(*)                                              AS total_appointed,
       count(*) FILTER (WHERE e.verification = 'Fully verified')   AS fully_verified,
       count(*) FILTER (WHERE e.verification = 'Has pending')      AS with_pending,
       count(*) FILTER (WHERE e.verification = 'Has not verified') AS not_verified,
       count(*) FILTER (WHERE e.gender = 'Male')             AS male,
       count(*) FILTER (WHERE e.gender = 'Female')           AS female,
       count(*) FILTER (WHERE e.deo_comments IS NULL OR e.deo_comments = '')   AS awaiting_deo_comment,
       count(*) FILTER (WHERE e.grievance IS NOT NULL AND e.grievance <> ''
                          AND (e.director_decision IS NULL OR e.director_decision = 'Under review')) AS open_grievances
FROM phases p JOIN v_employee_verification e ON e.phase_id = p.id
GROUP BY p.id, p.name, p.status, e.district;

CREATE VIEW v_family_quota_stats AS
SELECT district, status, applicant_gender, count(*) AS applications
FROM family_quota_applications
GROUP BY district, status, applicant_gender;

