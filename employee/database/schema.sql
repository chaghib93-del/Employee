BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;   -- gen_random_uuid(), crypt() for password hashes
CREATE EXTENSION IF NOT EXISTS citext;     -- case-insensitive usernames

-- ---------------------------------------------------------------------
-- Helper trigger: keep updated_at current
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END $$;

-- ---------------------------------------------------------------------
-- Districts (reference data)
-- ---------------------------------------------------------------------
CREATE TABLE districts (
  name        text PRIMARY KEY,
  created_at  timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- Users and roles
--   dir   = Director / Admin level
--   ad    = Assistant Director
--   deo   = District Education Officer (needs a district)
--   entry = Entry level operator       (needs a district)
--   ops   = Office entry operator      (created by an Assistant Director, works for any district)
-- password_hash holds a bcrypt hash (never a plain password).
-- ---------------------------------------------------------------------
CREATE TABLE users (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  username       citext NOT NULL UNIQUE,
  password_hash  text   NOT NULL,
  role           text   NOT NULL CHECK (role IN ('dir', 'ad', 'deo', 'entry', 'ops')),
  district       text   REFERENCES districts(name) ON UPDATE CASCADE,
  created_by     uuid   REFERENCES users(id) ON DELETE SET NULL,
  is_active      boolean NOT NULL DEFAULT true,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  CHECK (role NOT IN ('deo', 'entry') OR district IS NOT NULL)
);
CREATE INDEX users_role_district_idx ON users (role, district);
CREATE TRIGGER users_updated_at BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------
-- Appointment phases
-- A phase is generated by the Director, assigned to all districts or to
-- specific districts, and marked completed when the process is finished.
-- ---------------------------------------------------------------------
CREATE TABLE phases (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name          text NOT NULL,
  status        text NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'Completed')),
  all_districts boolean NOT NULL DEFAULT true,   -- false: see phase_districts
  created_by    uuid REFERENCES users(id) ON DELETE SET NULL,
  created_at    timestamptz NOT NULL DEFAULT now(),
  completed_at  timestamptz,
  CHECK ((status = 'Completed') = (completed_at IS NOT NULL))
);
CREATE UNIQUE INDEX phases_name_key ON phases (lower(name));

CREATE TABLE phase_districts (
  phase_id  uuid NOT NULL REFERENCES phases(id) ON DELETE CASCADE,
  district  text NOT NULL REFERENCES districts(name) ON UPDATE CASCADE ON DELETE CASCADE,
  PRIMARY KEY (phase_id, district)
);

-- Does this phase apply to this district?
CREATE OR REPLACE FUNCTION phase_covers(p_phase uuid, p_district text) RETURNS boolean
LANGUAGE sql STABLE AS $$
  SELECT EXISTS (
    SELECT 1 FROM phases p
    WHERE p.id = p_phase
      AND (p.all_districts
           OR EXISTS (SELECT 1 FROM phase_districts d WHERE d.phase_id = p.id AND d.district = p_district))
  );
$$;

-- Phases visible to a district (use for DEOs and entry operators)
CREATE OR REPLACE FUNCTION phases_for_district(p_district text) RETURNS SETOF phases
LANGUAGE sql STABLE AS $$
  SELECT p.* FROM phases p WHERE phase_covers(p.id, p_district) ORDER BY p.created_at;
$$;

-- ---------------------------------------------------------------------
-- Employee records (the main data table)
-- Degree status values: Verified, Not verified, Pending, N/A
-- ---------------------------------------------------------------------
CREATE TABLE employees (
  id                 uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  phase_id           uuid NOT NULL REFERENCES phases(id) ON DELETE CASCADE,
  district           text NOT NULL REFERENCES districts(name) ON UPDATE CASCADE,
  name               text NOT NULL,
  father_name        text,
  gender             text NOT NULL DEFAULT 'Male' CHECK (gender IN ('Male', 'Female')),
  designation        text NOT NULL,

  matric_no          text NOT NULL DEFAULT '',
  matric_status      text NOT NULL DEFAULT 'N/A' CHECK (matric_status IN ('Verified', 'Not verified', 'Pending', 'N/A')),
  fsc_no             text NOT NULL DEFAULT '',
  fsc_status         text NOT NULL DEFAULT 'N/A' CHECK (fsc_status    IN ('Verified', 'Not verified', 'Pending', 'N/A')),
  ba_no              text NOT NULL DEFAULT '',
  ba_status          text NOT NULL DEFAULT 'N/A' CHECK (ba_status     IN ('Verified', 'Not verified', 'Pending', 'N/A')),
  prof_no            text NOT NULL DEFAULT '',
  prof_status        text NOT NULL DEFAULT 'N/A' CHECK (prof_status   IN ('Verified', 'Not verified', 'Pending', 'N/A')),

  grievance          text,                                   -- written by the entry operator
  deo_comments       text,                                   -- DEO comments
  director_decision  text CHECK (director_decision IN ('Under review', 'Appointment upheld', 'Grievance accepted', 'Referred back to DEO')),
  director_comments  text,                                   -- Div: Director comments

  closed_at          timestamptz,                            -- set when the phase is completed
  closed_by          uuid REFERENCES users(id) ON DELETE SET NULL,
  created_by         uuid REFERENCES users(id) ON DELETE SET NULL,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX employees_phase_district_idx ON employees (phase_id, district);
CREATE INDEX employees_name_idx ON employees (lower(name));

CREATE TRIGGER employees_updated_at BEFORE UPDATE ON employees
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Rule: records can be entered only while a phase assigned to the district is in progress.
CREATE OR REPLACE FUNCTION employees_guard_insert() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.closed_at IS NULL AND NOT EXISTS (
       SELECT 1 FROM phases p
       WHERE p.id = NEW.phase_id AND p.status = 'Active' AND phase_covers(p.id, NEW.district)) THEN
    RAISE EXCEPTION 'Data entry is closed: no phase in progress for district % in this phase', NEW.district
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER employees_guard_insert BEFORE INSERT ON employees
  FOR EACH ROW EXECUTE FUNCTION employees_guard_insert();

-- Rule: a closed record cannot be edited (a reopen sets closed_at back to NULL and is allowed).
CREATE OR REPLACE FUNCTION employees_guard_update() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.closed_at IS NOT NULL AND NEW.closed_at IS NOT NULL THEN
    RAISE EXCEPTION 'This record is closed because its appointment phase is completed'
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER employees_guard_update BEFORE UPDATE ON employees
  FOR EACH ROW EXECUTE FUNCTION employees_guard_update();

-- Rule: a degree with a number starts as Pending, a blank degree is N/A.
-- (The Director level sets Verified / Not verified afterwards.)
CREATE OR REPLACE FUNCTION employees_auto_status() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.matric_no <> '' AND NEW.matric_status = 'N/A' THEN NEW.matric_status := 'Pending'; END IF;
    IF NEW.fsc_no    <> '' AND NEW.fsc_status    = 'N/A' THEN NEW.fsc_status    := 'Pending'; END IF;
    IF NEW.ba_no     <> '' AND NEW.ba_status     = 'N/A' THEN NEW.ba_status     := 'Pending'; END IF;
    IF NEW.prof_no   <> '' AND NEW.prof_status   = 'N/A' THEN NEW.prof_status   := 'Pending'; END IF;
  ELSE
    IF NEW.matric_no IS DISTINCT FROM OLD.matric_no AND NEW.matric_status = OLD.matric_status
      THEN NEW.matric_status := CASE WHEN NEW.matric_no <> '' THEN 'Pending' ELSE 'N/A' END; END IF;
    IF NEW.fsc_no IS DISTINCT FROM OLD.fsc_no AND NEW.fsc_status = OLD.fsc_status
      THEN NEW.fsc_status := CASE WHEN NEW.fsc_no <> '' THEN 'Pending' ELSE 'N/A' END; END IF;
    IF NEW.ba_no IS DISTINCT FROM OLD.ba_no AND NEW.ba_status = OLD.ba_status
      THEN NEW.ba_status := CASE WHEN NEW.ba_no <> '' THEN 'Pending' ELSE 'N/A' END; END IF;
    IF NEW.prof_no IS DISTINCT FROM OLD.prof_no AND NEW.prof_status = OLD.prof_status
      THEN NEW.prof_status := CASE WHEN NEW.prof_no <> '' THEN 'Pending' ELSE 'N/A' END; END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER employees_auto_status BEFORE INSERT OR UPDATE ON employees
  FOR EACH ROW EXECUTE FUNCTION employees_auto_status();

-- ---------------------------------------------------------------------
-- Family quota: new appointments for the family of deceased employees
-- ---------------------------------------------------------------------
CREATE TABLE family_quota_applications (
  id                    uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  district              text NOT NULL REFERENCES districts(name) ON UPDATE CASCADE,

  deceased_name         text NOT NULL,
  deceased_personal_no  text,
  deceased_designation  text NOT NULL,
  deceased_bps          smallint CHECK (deceased_bps BETWEEN 1 AND 22),
  date_of_death         date NOT NULL,

  applicant_name        text NOT NULL,
  relation              text NOT NULL CHECK (relation IN ('Son', 'Daughter', 'Wife', 'Husband', 'Brother', 'Sister')),
  applicant_gender      text GENERATED ALWAYS AS (
                          CASE WHEN relation IN ('Son', 'Husband', 'Brother') THEN 'Male' ELSE 'Female' END
                        ) STORED,
  applicant_dob         date NOT NULL,
  qualification         text NOT NULL,
  post_applied          text NOT NULL,

  status                text NOT NULL DEFAULT 'Applied' CHECK (status IN (
                          'Applied', 'Recommended by DEO', 'Not recommended by DEO',
                          'Recommend', 'In process', 'On held', 'Objection',
                          'Approved', 'On hold', 'Rejected', 'Appointed')),   -- last four: older statuses
  deo_recommendation    text CHECK (deo_recommendation IN ('Recommended', 'Not recommended')),
  deo_comments          text,
  deo_edited            boolean NOT NULL DEFAULT false,      -- the DEO edited the details
  director_comments     text,                                -- Div: Director comments
  order_no              text,                                -- older appointment order fields
  order_date            date,
  appointed_at          timestamptz,

  created_by            uuid REFERENCES users(id) ON DELETE SET NULL,
  created_at            timestamptz NOT NULL DEFAULT now(),
  updated_at            timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX fq_district_status_idx ON family_quota_applications (district, status);
CREATE INDEX fq_search_idx ON family_quota_applications (lower(applicant_name), lower(deceased_name));
CREATE TRIGGER fq_updated_at BEFORE UPDATE ON family_quota_applications
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------
-- Notices and shared documents
-- ---------------------------------------------------------------------
CREATE TABLE notices (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  title       text NOT NULL,
  body        text NOT NULL,
  audience    text NOT NULL DEFAULT 'everyone' CHECK (audience IN ('everyone', 'deo', 'entry', 'ad')),
  created_by  uuid REFERENCES users(id) ON DELETE SET NULL,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE documents (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  title        text NOT NULL,
  category     text,
  audience     text NOT NULL DEFAULT 'director_level' CHECK (audience IN ('all_deos', 'district_deos', 'director_level')),
  district     text REFERENCES districts(name) ON UPDATE CASCADE,
  uploaded_by  uuid REFERENCES users(id) ON DELETE SET NULL,
  created_at   timestamptz NOT NULL DEFAULT now(),
  CHECK (audience <> 'district_deos' OR district IS NOT NULL)
);

-- ---------------------------------------------------------------------
-- Files: verified degree scans, family quota documents, notice and
-- document attachments. Store the file in Vercel Blob and keep its URL in
-- blob_url (recommended), or keep small files in the content column.
-- ---------------------------------------------------------------------
CREATE TABLE files (
  id                 uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  employee_id        uuid REFERENCES employees(id) ON DELETE CASCADE,
  fq_application_id  uuid REFERENCES family_quota_applications(id) ON DELETE CASCADE,
  notice_id          uuid REFERENCES notices(id) ON DELETE CASCADE,
  document_id        uuid REFERENCES documents(id) ON DELETE CASCADE,
  slot               text,            -- employees: matric | fsc | ba | prof ; family quota: death | heir
  file_name          text   NOT NULL,
  mime_type          text   NOT NULL,
  size_bytes         bigint NOT NULL CHECK (size_bytes >= 0 AND size_bytes <= 26214400),   -- 25 MB
  blob_url           text,
  content            bytea,
  uploaded_by        uuid REFERENCES users(id) ON DELETE SET NULL,
  created_at         timestamptz NOT NULL DEFAULT now(),
  CHECK (num_nonnulls(employee_id, fq_application_id, notice_id, document_id) = 1),
  CHECK (num_nonnulls(blob_url, content) = 1),
  CHECK (employee_id IS NULL OR slot IN ('matric', 'fsc', 'ba', 'prof')),
  CHECK (fq_application_id IS NULL OR slot IN ('death', 'heir')),
  CHECK (employee_id IS NULL AND fq_application_id IS NULL
         OR mime_type IN ('application/pdf', 'image/jpeg', 'image/png')),
  CHECK (employee_id IS NULL OR size_bytes <= 10485760),
  CHECK (fq_application_id IS NULL OR size_bytes <= 10485760)
);
-- one verified degree file per degree, one document per family quota slot
CREATE UNIQUE INDEX files_employee_slot_key ON files (employee_id, slot)       WHERE employee_id IS NOT NULL;
CREATE UNIQUE INDEX files_fq_slot_key       ON files (fq_application_id, slot) WHERE fq_application_id IS NOT NULL;
CREATE INDEX files_notice_idx   ON files (notice_id)   WHERE notice_id IS NOT NULL;
CREATE INDEX files_document_idx ON files (document_id) WHERE document_id IS NOT NULL;

-- ---------------------------------------------------------------------
